"""Shared helpers: styling, cached data loaders and decision recording."""
import json
from pathlib import Path

import pandas as pd
import streamlit as st

APP_DIR = Path(__file__).parent
DATA_DIR = APP_DIR / "data"

# Decisions the groups make, stored under plain session-state keys so they
# survive page switches (widget keys are dropped when their page isn't rendered).
DECISION_KEYS = [
    "initial_verdict",
    "initial_reason",
    "final_verdict",
    "final_reason",
    "conditions",
    "owner",
    "pause_criteria",
]


def load_css():
    """Inject the shared stylesheet (Lexend, navy text, tab styling)."""
    css = (APP_DIR / "styles.css").read_text(encoding="utf-8")
    st.html(f"<style>{css}</style>")


def init_state():
    for key in DECISION_KEYS:
        st.session_state.setdefault(key, None)


def record_decision(key: str, value) -> None:
    st.session_state[key] = value


def get_decision(key: str):
    return st.session_state.get(key)


@st.cache_data
def load_meta() -> dict:
    return json.loads((DATA_DIR / "meta.json").read_text(encoding="utf-8"))


@st.cache_data
def load_features() -> dict:
    return json.loads((DATA_DIR / "features.json").read_text(encoding="utf-8"))


@st.cache_data
def load_predictions() -> pd.DataFrame:
    return pd.read_csv(DATA_DIR / "test_predictions.csv")


def task_box(text: str) -> None:
    st.info(f"**TASK:** {text}")


def stage_header(title: str, subtitle: str | None = None) -> None:
    st.title(title)
    if subtitle:
        st.markdown(subtitle)


def synthetic_notice() -> None:
    st.caption(
        "All data in this exercise is **synthetic**: it was generated by a computer "
        "to behave like hospital discharge data. No real patients are involved."
    )


def stub(title: str, built_in: str) -> None:
    """Placeholder page for a stage that is built in a later chunk."""
    stage_header(title)
    st.info(f"This stage is still being built ({built_in}).")
    synthetic_notice()


def factual_check(answer: str | None, correct: str, explanation: str) -> None:
    """Immediate feedback for an objectively answerable question (not for judgement calls)."""
    if answer is None:
        return
    if answer == correct:
        st.success(f"Correct. {explanation}")
    else:
        st.warning(f"Not quite. {explanation}")


@st.cache_data
def load_shap_summary() -> dict:
    return json.loads((DATA_DIR / "shap_summary.json").read_text(encoding="utf-8"))


def capacity() -> int:
    """The call capacity (patients phoned per 1,000 discharges) the group has chosen."""
    return int(st.session_state.get("capacity_choice") or 100)


@st.cache_data
def load_friday() -> dict:
    return json.loads((DATA_DIR / "friday.json").read_text(encoding="utf-8"))


@st.cache_data
def load_shap(model: str = "v2") -> pd.DataFrame:
    return pd.read_csv(DATA_DIR / f"shap_{model}.csv")


@st.cache_data
def load_patient_values() -> pd.DataFrame:
    return pd.read_csv(DATA_DIR / "shap_patient_values.csv")


def next_stage(path: str, title: str, ready: bool, waiting: str) -> None:
    """Show a button to the next stage once this one is done, and say how else to get there."""
    st.divider()
    if ready:
        st.success("You have done everything you need to on this page.")
        st.page_link(path, label=f"Next: {title}", icon=":material/arrow_forward:")
        st.caption("You can also move on by clicking the next stage in the navigation bar at the top of the page.")
    else:
        st.caption(waiting)
