"""Shared helpers: styling, cached data loaders and decision recording."""
import json
from pathlib import Path

import pandas as pd
import streamlit as st

APP_DIR = Path(__file__).parent
DATA_DIR = APP_DIR / "data"

# Decisions the groups make, stored under plain session-state keys so they
# survive page switches (widget keys are dropped when their page isn't rendered).
DECISION_KEYS = [
    "initial_verdict",
    "initial_reason",
    "final_verdict",
    "final_reason",
    "conditions",
    "owner",
    "pause_criteria",
]


def load_css():
    """Inject the shared stylesheet (Lexend, navy text, tab styling)."""
    css = (APP_DIR / "styles.css").read_text(encoding="utf-8")
    st.html(f"<style>{css}</style>")


def init_state():
    for key in DECISION_KEYS:
        st.session_state.setdefault(key, None)


def record_decision(key: str, value) -> None:
    st.session_state[key] = value


def get_decision(key: str):
    return st.session_state.get(key)


@st.cache_data
def load_meta() -> dict:
    return json.loads((DATA_DIR / "meta.json").read_text(encoding="utf-8"))


@st.cache_data
def load_features() -> dict:
    return json.loads((DATA_DIR / "features.json").read_text(encoding="utf-8"))


@st.cache_data
def load_predictions() -> pd.DataFrame:
    return pd.read_csv(DATA_DIR / "test_predictions.csv")


def task_box(text: str) -> None:
    st.info(f"**TASK:** {text}")


# Rough minutes for a small group on each page, shown as a badge. Unpiloted estimates for a
# 42-minute session (debrief and the extension are extra). Keep in step with the timings table in README.md.
STAGE_MINUTES = {
    "briefing": 3,
    "stage1": 4,
    "stage2": 5,
    "stage3": 8,
    "stage4": 10,
    "stage5": 7,
    "stage6": 5,
}

# Discussion prompts, moved off the stage pages to an extension at the end of the sign-off page
# so they don't derail the core route. (stage, prompt)
